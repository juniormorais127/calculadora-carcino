import { test, expect } from '@playwright/test';

test('estatísticas locais sem login: contatos, persistência, CSV e limpeza', async ({ page, context }, testInfo) => {
  await page.setViewportSize({ width: 426, height: 812 });
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await context.route('https://wa.me/**', route => route.abort());
  await page.goto('./');
  await expect(page.getByText('Carregando banco de dados local...')).toBeHidden();
  await page.getByRole('button', { name: 'Onde Comprar', exact: true }).click();
  await page.getByRole('button', { name: 'Estatísticas de teste', exact: true }).click();
  await expect(page.getByText('Dados somente deste navegador.', { exact: false })).toBeVisible();
  await expect(page.locator('dl').getByText('1', { exact: true })).toBeVisible();
  await expect(page.getByText('Nenhum clique registrado neste período.')).toBeVisible();
  await page.getByRole('button', { name: 'Voltar ao Mercado' }).click();
  const [popup] = await Promise.all([page.waitForEvent('popup'), page.getByRole('link', { name: 'WhatsApp', exact: true }).first().click()]);
  await popup.close();
  await page.getByRole('button', { name: 'Estatísticas de teste', exact: true }).click();
  await expect(page.getByText('WhatsApp:').locator('..')).toContainText('1');
  await expect(page.getByText('Jaguaribe Insumos Aquícolas', { exact: false })).toBeVisible();
  const downloadPromise = page.waitForEvent('download');
  await page.getByRole('button', { name: 'Exportar CSV' }).click();
  const download = await downloadPromise;
  expect(download.suggestedFilename()).toBe('estatisticas-locais-7-dias.csv');
  await page.screenshot({ path: testInfo.outputPath('analytics-mobile.png'), fullPage: true });
  await page.setViewportSize({ width: 1440, height: 900 });
  await page.screenshot({ path: testInfo.outputPath('analytics-desktop.png'), fullPage: true });
  await page.reload();
  await expect(page.getByText('Carregando banco de dados local...')).toBeHidden();
  await page.getByRole('button', { name: 'Onde Comprar', exact: true }).click();
  await page.getByRole('button', { name: 'Estatísticas de teste', exact: true }).click();
  await expect(page.getByText('WhatsApp:').locator('..')).toContainText('1');
  await expect(page.locator('dl').getByText('2', { exact: true }).first()).toBeVisible();
  await page.getByRole('button', { name: 'Limpar estatísticas de teste' }).click();
  await page.getByRole('button', { name: 'Apagar estatísticas', exact: true }).click();
  await expect(page.getByText('Nenhum clique registrado neste período.')).toBeVisible();
  expect(errors).toEqual([]);
});
